function round1(n: number): number {
  return Math.round(n * 10) / 10
}

export function chanceScore(competition: number): number {
  return Math.max(1, Math.min(10, 10 - competition))
}

export function totalScore(row: SchoolRow): number {
  const w = WEIGHTS
  return round1(
    row.campus * w.campus +
      row.dragon * w.dragon +
      row.s1 * w.s1 +
      row.news * w.news +
      row.housing * w.housing +
      row.active * w.active +
      chanceScore(row.competition) * w.chance,
  )
}

